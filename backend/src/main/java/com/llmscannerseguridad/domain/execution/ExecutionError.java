package com.llmscannerseguridad.domain.execution;

public enum ExecutionError {
    DNS_RESOLUTION_FAILED, TARGET_CONNECTION_FAILED, TARGET_TIMEOUT, HTTP_STATUS_ERROR,
    REQUEST_TOO_LARGE, RESPONSE_TOO_LARGE, RESPONSE_FORMAT_ERROR, RESPONSE_INVALID_JSON,
    RESPONSE_PATH_NOT_FOUND, RESPONSE_NOT_TEXT, EVIDENCE_LIMIT_EXCEEDED,
    TARGET_NOT_AUTHORIZED, TARGET_ADDRESS_BLOCKED, TARGET_TRANSPORT_REJECTED,
    TARGET_CONFIGURATION_INVALID, CREDENTIAL_UNAVAILABLE, SCAN_BUDGET_EXCEEDED,
    EXECUTION_INTERNAL_ERROR, EXECUTION_ABORTED, EXECUTION_INTERRUPTED;

    public boolean global() {
        return switch (this) {
            case TARGET_NOT_AUTHORIZED, TARGET_ADDRESS_BLOCKED, TARGET_TRANSPORT_REJECTED,
                    TARGET_CONFIGURATION_INVALID, CREDENTIAL_UNAVAILABLE, SCAN_BUDGET_EXCEEDED,
                    EXECUTION_INTERNAL_ERROR, EXECUTION_ABORTED, EXECUTION_INTERRUPTED -> true;
            default -> false;
        };
    }
}
